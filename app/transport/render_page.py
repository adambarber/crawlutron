"""The page surface the render phases call: shared Protocols, declared once."""

from __future__ import annotations

from collections.abc import Callable
from typing import Protocol


class GuardContext(Protocol):
    """The context surface the render uses: SSRF guard installs plus cookie harvest."""

    async def route(self, pattern: str, handler: Callable[..., object]) -> object: ...

    def route_web_socket(self, pattern: str, handler: Callable[..., object]) -> object: ...

    async def cookies(self, urls: str | list[str] | None = None) -> list[dict[str, str]]: ...


class PageElement(Protocol):
    """One matched DOM element: what the action verbs and screenshots call."""

    async def scroll_into_view_if_needed(self) -> object: ...

    async def is_visible(self) -> bool: ...

    async def click(self) -> object: ...

    async def screenshot(self) -> bytes: ...


class RenderPage(Protocol):
    """The page surface the render phases call; a double needs exactly this."""

    url: str
    context: GuardContext

    def on(self, event: str, handler: Callable[..., object]) -> object: ...

    async def goto(self, url: str, wait_until: str = "load", **kwargs: object) -> object: ...

    async def set_extra_http_headers(self, headers: dict[str, str]) -> object: ...

    async def evaluate(self, expression: str, *args: object, **kwargs: object) -> object: ...

    async def screenshot(self, **kwargs: object) -> bytes: ...

    async def content(self) -> str: ...

    async def close(self) -> object: ...

    async def query_selector(self, selector: str) -> PageElement | None: ...

    async def click(self, selector: str) -> object: ...

    async def fill(self, selector: str, value: str) -> object: ...

    async def hover(self, selector: str) -> object: ...

    async def wait_for_selector(
        self, selector: str, timeout: int | None = None, **kwargs: object
    ) -> object: ...
